#!/usr/bin/env python3
"""Regenerates the table of pinned speech-model files.

Downloads every file the app reads from the two Hugging Face repositories at the commits named in PINS, checks each
against the hash the Hub publishes for that commit, hashes it with SHA-256, and writes:

  DictationCore/Sources/DictationCore/PinnedModels.swift   what the app checks before Core ML reads a file
  scripts/models.lock                                      what scripts/fetch-models.sh downloads and checks

To move to a newer model, change a commit below, run this script, and review the diff. The files are listed the
way FluidAudio lists them: the Core ML bundles the app loads, and the .json and .txt files at the repository root.
"""
import hashlib
import json
import os
import shutil
import sys
import tempfile
import urllib.request

# (repository, commit, FluidAudio cache folder, Swift name, Core ML bundles the app loads)
PINS = [
    ("FluidInference/parakeet-tdt-0.6b-v2-coreml", "ee09c569f73759e6d44c9bd16766f477b2b36d39",
     "parakeet-tdt-0.6b-v2", "parakeetTDT",
     ["Preprocessor.mlmodelc", "Encoder.mlmodelc", "Decoder.mlmodelc", "JointDecision.mlmodelc"]),
    ("FluidInference/parakeet-ctc-110m-coreml", "accdafd8cf8a2ff1cabe3c11e54416b405d409aa",
     "parakeet-ctc-110m-coreml", "parakeetCTC",
     ["MelSpectrogram.mlmodelc", "AudioEncoder.mlmodelc"]),
]

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
swift_out = os.path.join(root, "DictationCore/Sources/DictationCore/PinnedModels.swift")
lock_out = os.path.join(root, "scripts/models.lock")


def get(url):
    with urllib.request.urlopen(url, timeout=120) as response:
        return response.read()


def listing(repo, commit):
    files = json.loads(get(f"https://huggingface.co/api/models/{repo}/tree/{commit}?recursive=true"))
    return {item["path"]: item for item in files if item["type"] == "file"}


def wanted(path, bundles):
    return path.split("/")[0] in bundles or ("/" not in path and path.endswith((".json", ".txt")))


def fetch(repo, commit, item, destination):
    path = item["path"]
    sha256, git_blob = hashlib.sha256(), hashlib.sha1(b"blob %d\0" % item["size"])
    os.makedirs(os.path.dirname(destination), exist_ok=True)
    request = urllib.request.Request(f"https://huggingface.co/{repo}/resolve/{commit}/{path}")
    size = 0
    with urllib.request.urlopen(request, timeout=120) as response, open(destination, "wb") as out:
        while chunk := response.read(1 << 20):
            out.write(chunk)
            sha256.update(chunk)
            git_blob.update(chunk)
            size += len(chunk)
    # The Hub publishes the SHA-256 of an LFS file and the git object id of any other.
    published = item.get("lfs", {}).get("oid")
    if size != item["size"] or (sha256.hexdigest() != published if published else git_blob.hexdigest() != item["oid"]):
        sys.exit(f"{repo}@{commit[:12]}: {path} does not match the hash the Hub publishes for it")
    return size, sha256.hexdigest()


def main():
    scratch = tempfile.mkdtemp(prefix="pin-models.")
    try:
        models = []
        for repo, commit, folder, name, bundles in PINS:
            tree = listing(repo, commit)
            paths = sorted(p for p in tree if wanted(p, bundles))
            missing = [b for b in bundles if not any(p.startswith(b + "/") for p in paths)]
            if missing:
                sys.exit(f"{repo}@{commit[:12]} has no {', '.join(missing)}")
            files = []
            for path in paths:
                size, digest = fetch(repo, commit, tree[path], os.path.join(scratch, folder, path))
                files.append((path, size, digest))
                print(f"{folder}/{path} {size}", file=sys.stderr)
            models.append((repo, commit, folder, name, files))
    finally:
        shutil.rmtree(scratch, ignore_errors=True)

    with open(swift_out, "w") as out:
        out.write("// Generated by scripts/pin-models.py. Do not edit.\n\n")
        out.write("public enum PinnedModels {\n")
        for repo, commit, folder, name, files in models:
            out.write(f"    public static let {name} = PinnedModel(\n")
            out.write(f'        repo: "{repo}",\n        commit: "{commit}",\n        folder: "{folder}",\n')
            out.write("        files: [\n")
            for path, size, digest in files:
                out.write(f'            ModelFile("{path}", size: {size}, sha256: "{digest}"),\n')
            out.write("        ])\n\n")
        out.write(f"    public static let all = [{', '.join(m[3] for m in models)}]\n}}\n")
    with open(lock_out, "w") as out:
        out.write("# Generated by scripts/pin-models.py. Do not edit.\n")
        out.write("# model REPOSITORY COMMIT FOLDER\n# SIZE SHA-256 PATH\n")
        for repo, commit, folder, name, files in models:
            out.write(f"model {repo} {commit} {folder}\n")
            for path, size, digest in files:
                out.write(f"{size} {digest} {path}\n")


main()
