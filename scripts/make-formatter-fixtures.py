#!/usr/bin/env python3
"""Regenerates the smart formatting parity fixtures from the training code, so the Swift port is checked against
the Python the model was trained and scored with.

usage: make-formatter-fixtures.py TRAINING_DIR MODEL_DIR FORMATTER_DIR

Run it with the training environment's Python (it needs torch and transformers). Only made-up example text goes
into the fixtures: the made-up test set, and fixed tricky words.
"""
import json
import os
import random
import sys

training, model_dir, formatter = sys.argv[1], sys.argv[2], sys.argv[3]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, training)
sys.path.insert(0, os.path.join(root, "bench"))
import torch  # noqa: E402
import train  # noqa: E402
from build_data2 import gaps_for  # noqa: E402
from cleanup import deterministic  # noqa: E402
from labels import decide, render  # noqa: E402

meta = json.load(open(f"{model_dir}/meta.json"))
tok = train.tokenizer_for(model_dir)
train.FEATURES = set(meta["features"])
model = train.Tagger(meta["base"], meta["vocab_size"])
model.load_state_dict(torch.load(f"{model_dir}/tagger.pt", map_location="cpu"))
model.eval()
c = json.load(open(f"{formatter}/formatter.json"))["cut"]
cut = {"brk": c["brk"], "item": c["item"], "quote": c["quote"], "drop": c["drop"], "min_words_for_breaks": c["minWordsForBreaks"]}
rows = json.load(open(f"{training}/data2/test_synth2.json"))
rnd = random.Random(5)
rnd.shuffle(rows)


def s(x):
    if any(ord(c) < 0x20 and c != "\n" for c in x):
        sys.exit(f"control character in {x!r}")
    return '"' + x.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def opt(x):
    return "nil" if x is None else s(x)


out = ["// Generated by scripts/make-formatter-fixtures.py from the training code. Do not edit.",
       "// Text is from the made-up test set only.", "@testable import DictationCore", ""]

tricky = ["Hello,", "don't", "I'm", "\"Quote\"", "e.g.", "3.5", "100%", "café", "naïve", "TL;DR", "U.S.", "Beehiiv",
          "re-run", "50/50", "#hashtag", "@mention", "🙂", "...", "(aside)", "O'Brien", "x86_64", "ProfitPilot"]
words = []
for r in rows[:60]:
    words += r["words"]
words = list(dict.fromkeys(tricky + words))[:400]
out.append("let bpeFixtures: [(word: String, ids: [Int])] = [")
for w in words:
    ids = tok([w], is_split_into_words=True, add_special_tokens=False)["input_ids"]
    out.append(f"    ({s(w)}, {ids}),")
out.append("]")
out.append("")

out.append("let encodeFixtures: [(words: [String], app: String?, gaps: [Double], ids: [Int])] = [")
for r in rows[60:90]:
    ids, _, _ = train.encode(tok, r["words"], app=r["app"], gaps=r["gaps"])
    if len(ids) > 256:
        continue
    out.append(f"    ([{', '.join(s(w) for w in r['words'])}], {opt(r['app'])}, {[float(g) for g in r["gaps"]]}, {ids}),")
out.append("]")
out.append("")

out.append("let layoutFixtures: [(words: [String], scores: [[Double]], expected: String)] = [")
picked = [r for r in rows[90:] if any(l["brk"] or l["item"] or l["qo"] for l in r["labels"])][:25] + rows[200:215]
for r in picked:
    probs = train.probabilities(model, tok, r["words"], "cpu", r["app"], r["gaps"])
    flat = [[round(v, 6) for name, _ in train.HEADS for v in p[name]] for p in probs]
    probs = [{name: row[o:o + n] for (name, n), o in zip(train.HEADS, [0, 3, 6, 8, 10, 12, 19])} for row in flat]
    expected = render(r["words"], decide(r["words"], probs, cut))
    out.append(f"    ([{', '.join(s(w) for w in r['words'])}], {flat}, {s(expected)}),")
out.append("]")
out.append("")

out.append("let pauseFixtures: [(text: String, raw: String, tokens: [(String, Double, Double)], expected: [Double]?)] = [")
for r in rows[215:245]:
    raw = r["spoken"]
    text = deterministic(raw)
    t, tokens = 0.1, []
    for w in raw.split():
        core, mark = (w[:-1], w[-1]) if w[-1] in ".,?!" and len(w) > 1 else (w, "")
        pieces = [core[i:i + 3] for i in range(0, len(core), 3)] or [core]
        for n, p in enumerate(pieces):
            tokens.append(((" " if n == 0 else "") + p, round(t, 2), round(t + 0.08, 2)))
            t += 0.08
        if mark:
            tokens.append((mark, round(t, 2), round(t + 0.08, 2)))
            t += 0.08
        t += rnd.choice([0.0, 0.0, 0.08, 0.16, 0.48, 1.2, 2.4])
    expected = gaps_for(text, raw, [list(x) for x in tokens])
    exp = "nil" if expected is None else str([round(g, 6) for g in expected])
    out.append(f"    ({s(text)}, {s(raw)}, [{', '.join(f'({s(a)}, {b}, {c})' for a, b, c in tokens)}], {exp}),")
out.append("]")

path = os.path.join(root, "DictationCore/Tests/DictationCoreTests/FormatterFixtures.swift")
open(path, "w").write("\n".join(out) + "\n")
print(f"wrote {len(words)} words, {len(picked)} layouts, 30 pause cases to {os.path.relpath(path, root)}")
