#!/bin/bash
# Regenerates the cleanup parity fixtures. Every line of bench/cleanup-inputs.txt goes through the bakeoff's
# measured bench/cleanup.py deterministic pass, and the input and output pairs become a Swift test fixture, so
# the Swift port is checked against the Python it replaces rather than against hand-copied strings.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
fixtures="$root/DictationCore/Tests/DictationCoreTests/CleanupFixtures.swift"
generated="$(python3 -I -B - "$root/bench" "$root/bench/cleanup-inputs.txt" <<'PY'
import sys
sys.path.insert(0, sys.argv[1])
from cleanup import PROPER, deterministic

def literal(s):
    if any(ord(c) < 0x20 for c in s):
        sys.exit(f"control character in {s!r}")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

inputs = [line.rstrip("\n") for line in open(sys.argv[2], encoding="utf-8") if line.strip()]
print("// Generated by scripts/make-cleanup-fixtures.sh from bench/cleanup-inputs.txt and bench/cleanup.py. Do not edit.")
print("let cleanupFixtureProperNouns = [" + ", ".join(literal(p) for p in PROPER) + "]")
print("let cleanupFixtures: [(input: String, expected: String)] = [")
for text in inputs:
    print(f"    ({literal(text)}, {literal(deterministic(text))}),")
print("]")
PY
)"
printf '%s\n' "$generated" > "$fixtures"
printf 'Wrote %s fixtures to %s.\n' "$(grep -c '^    (' "$fixtures")" "${fixtures#"$root/"}"
